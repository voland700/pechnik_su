import type { ImageMetadata } from 'astro';

const images = import.meta.glob<{ default: ImageMetadata }>('../../assets/images/montage/*.{jpg,png}', { eager: true });
export const montageImage = (name: string): ImageMetadata => {
  const image = images[`../../assets/images/montage/${name}`];
  if (!image) throw new Error(`Missing montage image: ${name}`);
  return image.default;
};

